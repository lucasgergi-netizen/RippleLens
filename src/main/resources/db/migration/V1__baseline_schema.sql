CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE,
    email VARCHAR(255) NOT NULL UNIQUE,
    full_name VARCHAR(255),
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(255)
);

CREATE TABLE assets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category VARCHAR(32),
    current_price NUMERIC(38, 2),
    daily_change_percentage NUMERIC(38, 2),
    description VARCHAR(255),
    name VARCHAR(255),
    quote_currency VARCHAR(255),
    symbol VARCHAR(255),
    unit VARCHAR(255)
);

CREATE TABLE commodities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    currency VARCHAR(255),
    daily_change_percentage NUMERIC(38, 2),
    name VARCHAR(255),
    price NUMERIC(38, 2),
    symbol VARCHAR(255),
    unit VARCHAR(255)
);

CREATE TABLE asset_price_points (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    observation_date DATE,
    price NUMERIC(38, 2),
    source VARCHAR(255),
    asset_id BIGINT NOT NULL REFERENCES assets(id)
);

CREATE TABLE asset_alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_type VARCHAR(64),
    baseline_daily_change_percentage NUMERIC(38, 2),
    baseline_price NUMERIC(38, 2),
    created_at TIMESTAMP WITH TIME ZONE,
    custom_name VARCHAR(255),
    enabled BOOLEAN NOT NULL,
    last_notification VARCHAR(255),
    notification_preference VARCHAR(32),
    recurring BOOLEAN NOT NULL,
    session_key VARCHAR(255),
    status VARCHAR(32),
    target_value NUMERIC(38, 2),
    triggered_at TIMESTAMP WITH TIME ZONE,
    asset_id BIGINT NOT NULL REFERENCES assets(id)
);

CREATE TABLE portfolio_holdings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    average_cost NUMERIC(38, 2),
    created_at TIMESTAMP WITH TIME ZONE,
    quantity NUMERIC(38, 2),
    session_key VARCHAR(255),
    updated_at TIMESTAMP WITH TIME ZONE,
    asset_id BIGINT NOT NULL REFERENCES assets(id),
    CONSTRAINT uk_portfolio_session_asset UNIQUE (session_key, asset_id)
);

CREATE TABLE recent_asset_views (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_key VARCHAR(255),
    viewed_at TIMESTAMP WITH TIME ZONE,
    asset_id BIGINT NOT NULL REFERENCES assets(id),
    CONSTRAINT uk_recent_session_asset UNIQUE (session_key, asset_id)
);

CREATE TABLE user_preferences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    default_category VARCHAR(32),
    default_range_key VARCHAR(255),
    display_currency VARCHAR(255),
    session_key VARCHAR(255) UNIQUE,
    show_welcome_screen BOOLEAN NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE watchlist_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE,
    session_key VARCHAR(255),
    asset_id BIGINT NOT NULL REFERENCES assets(id),
    CONSTRAINT uk_watchlist_session_asset UNIQUE (session_key, asset_id)
);

CREATE INDEX idx_alerts_session ON asset_alerts(session_key);
CREATE INDEX idx_portfolio_session ON portfolio_holdings(session_key);
CREATE INDEX idx_recent_session ON recent_asset_views(session_key);
CREATE INDEX idx_watchlist_session ON watchlist_items(session_key);
CREATE INDEX idx_price_asset_date ON asset_price_points(asset_id, observation_date);
